CREATE TABLE IF NOT EXISTS roles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(60) NOT NULL UNIQUE,
 permisos JSON NOT NULL, protegido TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, rol_id BIGINT UNSIGNED NOT NULL,
 nombre VARCHAR(150) NOT NULL, nombre_usuario VARCHAR(60) NOT NULL UNIQUE,
 contrasena_hash VARCHAR(255) NOT NULL, activo TINYINT(1) NOT NULL DEFAULT 1,
 cambio_obligatorio TINYINT(1) NOT NULL DEFAULT 1, ultimo_acceso TIMESTAMP NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (rol_id) REFERENCES roles(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS intentos_acceso (
 clave CHAR(64) PRIMARY KEY, inicio BIGINT NOT NULL, intentos INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS bitacora_actividad (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, usuario_id BIGINT UNSIGNED NULL,
 usuario_nombre VARCHAR(150) NOT NULL, tipo VARCHAR(40) NOT NULL,
 referencia VARCHAR(100) NOT NULL, resumen VARCHAR(500) NOT NULL, detalle JSON NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY ix_bitacora_fecha(creado_en,id), KEY ix_bitacora_actor(usuario_id,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resultados (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, referencia VARCHAR(100) NOT NULL UNIQUE,
 version INT UNSIGNED NOT NULL DEFAULT 1, estado ENUM('borrador','validado') NOT NULL DEFAULT 'borrador',
 creado_por BIGINT UNSIGNED NOT NULL, actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resultado_versiones (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, resultado_id BIGINT UNSIGNED NOT NULL,
 version INT UNSIGNED NOT NULL, contenido TEXT NOT NULL, motivo VARCHAR(500) NOT NULL,
 usuario_id BIGINT UNSIGNED NOT NULL, creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_resultado_version(resultado_id,version), FOREIGN KEY (resultado_id) REFERENCES resultados(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resultado_validaciones (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, resultado_id BIGINT UNSIGNED NOT NULL,
 version INT UNSIGNED NOT NULL, usuario_id BIGINT UNSIGNED NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_validacion(resultado_id,version),
 FOREIGN KEY (resultado_id,version) REFERENCES resultado_versiones(resultado_id,version)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS resultado_entregas (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, resultado_id BIGINT UNSIGNED NOT NULL,
 version INT UNSIGNED NOT NULL, usuario_id BIGINT UNSIGNED NOT NULL, destinatario VARCHAR(150) NOT NULL,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (resultado_id,version) REFERENCES resultado_validaciones(resultado_id,version)
) ENGINE=InnoDB;
