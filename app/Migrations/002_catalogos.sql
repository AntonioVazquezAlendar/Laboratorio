CREATE TABLE IF NOT EXISTS tipos_muestra (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, recipiente VARCHAR(150) NOT NULL DEFAULT '',
 indicaciones TEXT NOT NULL, activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS metodos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, descripcion TEXT NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS companias (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, razon_social VARCHAR(200) NOT NULL DEFAULT '', rfc VARCHAR(13) NOT NULL DEFAULT '',
 contacto VARCHAR(150) NOT NULL DEFAULT '', telefono VARCHAR(30) NOT NULL DEFAULT '', correo VARCHAR(150) NOT NULL DEFAULT '',
 direccion VARCHAR(500) NOT NULL DEFAULT '', notas TEXT NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS medicos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, apellidos VARCHAR(150) NOT NULL DEFAULT '', cedula VARCHAR(30) NOT NULL DEFAULT '',
 especialidad VARCHAR(150) NOT NULL DEFAULT '', telefono VARCHAR(30) NOT NULL DEFAULT '', correo VARCHAR(150) NOT NULL DEFAULT '',
 direccion VARCHAR(500) NOT NULL DEFAULT '', notas TEXT NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS pacientes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, apellidos VARCHAR(150) NOT NULL,
 fecha_nacimiento DATE NULL, sexo ENUM('femenino','masculino','otro','no_especificado') NOT NULL DEFAULT 'no_especificado',
 telefono VARCHAR(30) NOT NULL DEFAULT '', correo VARCHAR(150) NOT NULL DEFAULT '', direccion VARCHAR(500) NOT NULL DEFAULT '',
 medico_id BIGINT UNSIGNED NULL, compania_id BIGINT UNSIGNED NULL, notas TEXT NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (medico_id) REFERENCES medicos(id), FOREIGN KEY (compania_id) REFERENCES companias(id),
 KEY ix_paciente_nombre(apellidos,nombre)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS analitos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, unidad VARCHAR(40) NOT NULL DEFAULT '',
 tipo_resultado ENUM('numerico','cualitativo','texto') NOT NULL DEFAULT 'numerico',
 decimales TINYINT UNSIGNED NOT NULL DEFAULT 2, metodo_id BIGINT UNSIGNED NULL, notas TEXT NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (metodo_id) REFERENCES metodos(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS estudios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, codigo VARCHAR(30) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL, area VARCHAR(100) NOT NULL DEFAULT '',
 tipo_muestra_id BIGINT UNSIGNED NULL, metodo_id BIGINT UNSIGNED NULL,
 tiempo_entrega VARCHAR(100) NOT NULL DEFAULT '', indicaciones TEXT NOT NULL,
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (tipo_muestra_id) REFERENCES tipos_muestra(id), FOREIGN KEY (metodo_id) REFERENCES metodos(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS estudio_analitos (
 estudio_id BIGINT UNSIGNED NOT NULL, analito_id BIGINT UNSIGNED NOT NULL, orden INT UNSIGNED NOT NULL,
 PRIMARY KEY(estudio_id,analito_id), UNIQUE KEY uq_estudio_orden(estudio_id,orden),
 FOREIGN KEY (estudio_id) REFERENCES estudios(id), FOREIGN KEY (analito_id) REFERENCES analitos(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS precios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, estudio_id BIGINT UNSIGNED NOT NULL, compania_id BIGINT UNSIGNED NULL,
 compania_ambito BIGINT UNSIGNED GENERATED ALWAYS AS (IFNULL(compania_id,0)) STORED,
 importe DECIMAL(12,2) NOT NULL, moneda CHAR(3) NOT NULL DEFAULT 'MXN',
 activo TINYINT(1) NOT NULL DEFAULT 1, version INT UNSIGNED NOT NULL DEFAULT 1,
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_precio_estudio_compania(estudio_id,compania_ambito),
 FOREIGN KEY (estudio_id) REFERENCES estudios(id), FOREIGN KEY (compania_id) REFERENCES companias(id)
) ENGINE=InnoDB;
